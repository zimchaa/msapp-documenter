#!/usr/bin/env python3
"""msapp-documenter command line.

  extract  <app.msapp | solution.zip> --out DIR [--app NAME]
           Deterministic stage: clean YAML source, app_model.json, Markdown facts doc and AI-context chunks.
  render   --out DIR [--template company.pptx]
           Re-renders Markdown + AI chunks and builds the PowerPoint, merging DIR/interpretation.json if present.
  check    <app.msapp>
           Runs extract twice into temp folders and confirms the outputs are byte-identical.
"""
import argparse
import hashlib
import json
import os
import re
import shutil
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import yaml  # noqa: E402

import msapp_analyze  # noqa: E402
import msapp_model  # noqa: E402
import render_md  # noqa: E402
import wireframe  # noqa: E402
import callouts  # noqa: E402

GENERATOR_VERSION = "0.1.0"
SKILL_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


# ----------------------------------------------------------------------------- YAML output

class _Dumper(yaml.SafeDumper):
    pass


def _str_rep(dumper, data):
    style = "|" if "\n" in data else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", data, style=style)


_Dumper.add_representer(str, _str_rep)


def to_pa_yaml(node):
    body = {"Control": node["type"]}
    if node.get("properties"):
        body["Properties"] = {k: "=" + v for k, v in node["properties"].items()}
    if node.get("children"):
        body["Children"] = [to_pa_yaml(c) for c in node["children"]]
    return {node["name"]: body}


def dump_yaml(obj, header):
    return header + yaml.dump(obj, Dumper=_Dumper, sort_keys=False, allow_unicode=True, width=120)


# ----------------------------------------------------------------------------- stages

def extract(input_path, out_dir, app_hint=None):
    raw = msapp_model.load(input_path, app_hint)
    analysis = msapp_analyze.analyze(raw)

    names = sorted({v["name"] for v in analysis["variables"]} | {c["name"] for c in analysis["collections"]},
                   key=len, reverse=True)
    symbols_re = re.compile(r"(?<![\w.])(" + "|".join(re.escape(n) for n in names) + r")(?![\w])") if names else None

    os.makedirs(out_dir, exist_ok=True)
    src = os.path.join(out_dir, "source")
    if os.path.isdir(src):
        shutil.rmtree(src)
    os.makedirs(os.path.join(src, "screens"))

    header = ("# Clean source generated by msapp-documenter. Layout, static styling, default values and empty\n"
              "# handlers are removed; every formula shown is the app's own text (Power Apps YAML style, '=' prefix).\n")
    rules_total = sum(len(n["rules"]) for root in [raw["app_node"]] + raw["screens"] + raw["components"]
                      for n in msapp_model.walk(root))
    clean_bytes = 0

    def count_props(t):
        return len(t.get("properties", {})) + sum(count_props(c) for c in t.get("children", []))

    rules_kept = 0
    app_tree = msapp_model.clean_tree(raw["app_node"], symbols_re)
    app_tree["name"] = "App"
    text = dump_yaml(to_pa_yaml(app_tree), header)
    with open(os.path.join(src, "App.yaml"), "w", encoding="utf-8") as f:
        f.write(text)
    clean_bytes += len(text.encode())
    rules_kept += count_props(app_tree)

    screens = []
    for i, s in enumerate(raw["screens"], 1):
        tree = msapp_model.clean_tree(s, symbols_re)
        fname = f"{i:02d}-{render_md.slug(s['name'])}.yaml"
        text = dump_yaml(to_pa_yaml(tree), header + f"# Screen {i} of {len(raw['screens'])}: {s['name']}\n")
        with open(os.path.join(src, "screens", fname), "w", encoding="utf-8") as f:
            f.write(text)
        clean_bytes += len(text.encode())
        rules_kept += count_props(tree)
        screens.append({"name": s["name"], "file": fname, "tree": tree})
    for s, summ in zip(screens, analysis["screens"]):
        summ["file"] = s["file"]

    # Broad-strokes wireframes at the app's design size
    diag = os.path.join(out_dir, "diagrams", "screens")
    if os.path.isdir(diag):
        shutil.rmtree(diag)
    os.makedirs(diag)
    lay_info = raw["app_info"]["layout"]
    consts = wireframe.constants_from(raw["app_node"])
    all_formulas = msapp_analyze._formulas(raw)
    names = [x["name"] for x in raw["screens"]]
    for s, rs in zip(screens, raw["screens"]):
        wf = wireframe.screen_boxes(rs, lay_info.get("width"), lay_info.get("height"), constants=consts)
        s["callouts"] = callouts.build(rs, wf, all_formulas, names, raw["data_sources"], analysis["collections"])
        wf["svg"] = f"diagrams/screens/{s['file'][:-5]}.svg"
        with open(os.path.join(out_dir, wf["svg"]), "w", encoding="utf-8") as f:
            f.write(wireframe.svg(wf, s["name"]))
        s["wireframe"] = wf

    components = []
    if raw["components"]:
        os.makedirs(os.path.join(src, "components"))
    for c in raw["components"]:
        tree = msapp_model.clean_tree(c, symbols_re)
        fname = f"{render_md.slug(c['name'])}.yaml"
        text = dump_yaml(to_pa_yaml(tree), header)
        with open(os.path.join(src, "components", fname), "w", encoding="utf-8") as f:
            f.write(text)
        rules_kept += count_props(tree)
        components.append({"name": c["name"], "file": fname, "tree": tree})

    if raw["pa_yaml_files"]:
        os.makedirs(os.path.join(src, "original_pa_yaml"))
        for p, t in raw["pa_yaml_files"].items():
            with open(os.path.join(src, "original_pa_yaml", p.rsplit("/", 1)[-1]), "w", encoding="utf-8") as f:
                f.write(t)

    sev = {}
    for f in analysis["findings"]:
        sev[f["severity"]] = sev.get(f["severity"], 0) + 1
    ds = raw["data_sources"]
    stats = {
        "screens": len(raw["screens"]),
        "controls": sum(s["control_count"] for s in analysis["screens"]),
        "tables": sum(1 for d in ds if d["kind"] not in ("Collection", "Connector", "Power Automate flow")),
        "flows": sum(1 for d in ds if d["kind"] == "Power Automate flow"),
        "connectors": sum(1 for d in ds if d["kind"] == "Connector"),
        "variables": len(analysis["variables"]),
        "collections": len(analysis["collections"]),
        "findings": len(analysis["findings"]),
        "findings_by_severity": ", ".join(f"{sev[k]} {k}" for k in ("High", "Medium", "Low", "Info") if k in sev) or "none",
        "rules_total": rules_total,
        "rules_kept": rules_kept,
        "raw_kb": round(raw["source"]["raw_bytes"] / 1024),
        "clean_kb": round(clean_bytes / 1024),
    }
    model = {
        "generator_version": GENERATOR_VERSION,
        "source": raw["source"],
        "app_info": raw["app_info"],
        "app": app_tree,
        "screens": screens,
        "components": components,
        "data_sources": raw["data_sources"],
        "resources": raw["resources"],
        "app_checker": raw["app_checker"],
        "solution_flows": raw["solution_flows"],
        "analysis": analysis,
        "stats": stats,
    }
    os.makedirs(os.path.join(out_dir, "ai_context"), exist_ok=True)
    with open(os.path.join(out_dir, "ai_context", "app_model.json"), "w", encoding="utf-8") as f:
        json.dump(model, f, indent=1, ensure_ascii=False, sort_keys=False)
    render_text(model, {}, out_dir)
    return model


def load_model(out_dir):
    with open(os.path.join(out_dir, "ai_context", "app_model.json"), encoding="utf-8") as f:
        return json.load(f)


def load_interpretation(out_dir):
    p = os.path.join(out_dir, "interpretation.json")
    if not os.path.exists(p):
        return {}
    with open(p, encoding="utf-8") as f:
        return json.load(f)


def doc_basename(model):
    return re.sub(r"[^A-Za-z0-9]+", "_", model["app_info"]["name"]).strip("_") + "_documentation"


def render_text(model, ai, out_dir):
    with open(os.path.join(out_dir, doc_basename(model) + ".md"), "w", encoding="utf-8") as f:
        f.write(render_md.render_markdown(model, ai))
    render_md.write_ai_context(model, ai, out_dir)


def render(out_dir, template=None):
    import render_pptx
    model = load_model(out_dir)
    ai = load_interpretation(out_dir)
    render_text(model, ai, out_dir)
    template = template or os.path.join(SKILL_DIR, "assets", "default_template.pptx")
    pptx_path = os.path.join(out_dir, doc_basename(model) + ".pptx")
    render_pptx.build(model, ai, template, pptx_path)
    return pptx_path


def _tree_hash(d):
    h = hashlib.sha256()
    for root, _, files in sorted(os.walk(d)):
        for name in sorted(files):
            p = os.path.join(root, name)
            h.update(os.path.relpath(p, d).encode())
            with open(p, "rb") as f:
                h.update(f.read())
    return h.hexdigest()


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    e = sub.add_parser("extract")
    e.add_argument("input")
    e.add_argument("--out", required=True)
    e.add_argument("--app", help="canvas app name filter when the input is a solution .zip")
    r = sub.add_parser("render")
    r.add_argument("--out", required=True)
    r.add_argument("--template")
    c = sub.add_parser("check")
    c.add_argument("input")
    c.add_argument("--app")
    args = ap.parse_args()

    if args.cmd == "extract":
        m = extract(args.input, args.out, args.app)
        s = m["stats"]
        print(f"Extracted '{m['app_info']['name']}': {s['screens']} screens, {s['controls']} controls, "
              f"{s['tables']} data sources, {s['flows']} flows, {s['connectors']} connectors, "
              f"{s['findings']} findings ({s['findings_by_severity']}).")
        print(f"Formulas kept {s['rules_kept']}/{s['rules_total']}; raw {s['raw_kb']} KB -> clean {s['clean_kb']} KB.")
        print(f"Next: read {os.path.join(args.out, 'ai_context', 'index.md')}, write interpretation.json, then run render.")
    elif args.cmd == "render":
        p = render(args.out, args.template)
        print(f"Wrote {p}")
        print(f"Wrote {os.path.join(args.out, doc_basename(load_model(args.out)) + '.md')} and ai_context/")
    elif args.cmd == "check":
        with tempfile.TemporaryDirectory() as t1, tempfile.TemporaryDirectory() as t2:
            extract(args.input, t1, args.app)
            extract(args.input, t2, args.app)
            a, b = _tree_hash(t1), _tree_hash(t2)
        print("deterministic: identical outputs" if a == b else "NOT deterministic: outputs differ")
        print(a)
        sys.exit(0 if a == b else 1)


if __name__ == "__main__":
    main()
